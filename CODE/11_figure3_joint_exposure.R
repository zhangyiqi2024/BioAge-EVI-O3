# ---- nature-figure theme contract -----------------------------------------------
# Matches Nature-family double-column specs: 183 mm wide, 6.5–8 pt final text.
# Font: Arial (Nature standard sans-serif). Editable text via svglite.

palette_contract <- c(
  neutral_dark  = "#272727",
  neutral_mid   = "#767676",
  neutral_light = "#D8D8D8",
  signal_blue   = "#3182BD",
  signal_teal   = "#33B5A5",
  accent_red    = "#D24B40",
  accent_orange = "#E28E2C"
)

theme_nature <- function(base_size = 7, base_family = "Arial") {
  theme_classic(base_size = base_size, base_family = base_family) +
    theme(
      axis.line         = element_line(linewidth = 0.35, colour = "black"),
      axis.ticks        = element_line(linewidth = 0.35, colour = "black"),
      axis.title        = element_text(size = base_size),
      axis.text         = element_text(size = base_size - 0.5, colour = "#272727"),
      legend.title      = element_text(size = base_size - 0.5),
      legend.text       = element_text(size = base_size - 0.8),
      legend.key.size   = unit(0.6, "cm"),
      strip.background  = element_blank(),
      strip.text        = element_text(size = base_size, face = "bold", hjust = 0),
      plot.tag          = element_text(size = base_size + 2, face = "bold"),
      panel.grid        = element_blank(),
      legend.position   = "bottom",
      legend.direction  = "horizontal",
      legend.box        = "vertical",
      legend.margin     = margin(t = 2, b = 2),
      legend.key.width  = unit(0.6, "cm")
    )
}

theme_set(theme_nature())

save_pub_r <- function(plot, filename, width_mm = 183, height_mm = 210, dpi = 600) {
  w <- width_mm / 25.4
  h <- height_mm / 25.4
  dir.create(dirname(filename), recursive = TRUE, showWarnings = FALSE)

  # Primary: editable SVG
  svglite::svglite(paste0(filename, ".svg"), width = w, height = h)
  print(plot)
  dev.off()

  # PDF for submission
  grDevices::cairo_pdf(paste0(filename, ".pdf"), width = w, height = h,
                       family = "Arial")
  print(plot)
  dev.off()

  # TIFF for raster (Nature spec: 600 dpi, LZW compression)
  ragg::agg_tiff(paste0(filename, ".tiff"), width = w, height = h,
                 units = "in", res = dpi, compression = "lzw")
  print(plot)
  dev.off()

  # PNG preview (300 dpi, smaller file)
  ragg::agg_png(paste0(filename, ".png"), width = w, height = h,
                units = "in", res = 300)
  print(plot)
  dev.off()
}

# ---- paths (relative to project root) -------------------------------------------
cat("Reading input data...\n")
means_file    <- "output/tables/joint_association_adjusted_means_v4.csv"
contrast_file <- "output/tables/joint_association_contrasts_v4.csv"
out_stem      <- "output/figures/Figure3_joint_exposure_enhanced"

means_raw     <- read.csv(means_file, stringsAsFactors = FALSE)
contrast_raw  <- read.csv(contrast_file, stringsAsFactors = FALSE)

# ---- data constants -------------------------------------------------------------
group_levels <- c(
  "Low EVI / low O3",  "Low EVI / high O3",
  "High EVI / low O3", "High EVI / high O3"
)

# Colourblind-safe palette (Wong 2011, Nature Methods)
group_palette <- c(
  "Low EVI / low O3"   = "#0072B2",
  "Low EVI / high O3"  = "#E69F00",
  "High EVI / low O3"  = "#009E73",
  "High EVI / high O3" = "#CC79A7"
)

group_shapes <- c(
  "Low EVI / low O3"   = 16,   # filled circle
  "Low EVI / high O3"  = 18,   # diamond
  "High EVI / low O3"  = 17,   # triangle
  "High EVI / high O3" = 15    # square
)

buffer_lab <- c(
  "1KM"  = "1 km residential buffer",
  "500m" = "500 m residential buffer"
)

# ---- prepare means data ---------------------------------------------------------
means <- means_raw %>%
  mutate(
    exposure_group = factor(exposure_group, levels = group_levels),
    scale          = factor(scale, levels = c("1KM", "500m"))
  )

# ---- prepare contrast data ------------------------------------------------------
contrast_keep <- c(
  "Low EVI/high O3 vs reference",
  "High EVI/low O3 vs reference",
  "High EVI/high O3 vs reference",
  "O3 contrast within high EVI",
  "Difference-in-differences interaction"
)

contrast_label <- c(
  "Low EVI/high O3 vs reference"           = "Low EVI / high O₃  vs. Low EVI / low O₃",
  "High EVI/low O3 vs reference"           = "High EVI / low O₃  vs. Low EVI / low O₃",
  "High EVI/high O3 vs reference"          = "High EVI / high O₃  vs. Low EVI / low O₃",
  "O3 contrast within high EVI"            = "O₃ contrast within high EVI",
  "Difference-in-differences interaction"  = "DiD interaction  (departure from additivity)"
)

contrast_type <- c(
  "Low EVI/high O3 vs reference"           = "Pairwise vs. reference",
  "High EVI/low O3 vs reference"           = "Pairwise vs. reference",
  "High EVI/high O3 vs reference"          = "Pairwise vs. reference",
  "O3 contrast within high EVI"            = "Within-stratum",
  "Difference-in-differences interaction"  = "Interaction"
)

forest <- contrast_raw %>%
  filter(contrast %in% contrast_keep) %>%
  mutate(
    scale   = factor(scale, levels = c("1KM", "500m")),
    label   = contrast_label[contrast],
    ctype   = factor(contrast_type[contrast],
                     levels = c("Pairwise vs. reference",
                                "Within-stratum", "Interaction")),
    is_sig  = p < 0.05,
    ypos    = as.numeric(factor(label, levels = rev(unique(label))))
  )

cat(sprintf("  Means: %d rows   Contrasts: %d rows\n",
            nrow(means), nrow(forest)))

# ===========================================================================
# Panel a — Adjusted marginal means
# ===========================================================================
cat("Building panel a: adjusted marginal means...\n")

p_a <- ggplot(means, aes(x = exposure_group, y = adjusted_mean,
                          colour = exposure_group, shape = exposure_group)) +
  geom_hline(yintercept = 0, linetype = "dashed",
             colour = palette_contract["neutral_light"], linewidth = 0.35) +
  geom_errorbar(aes(ymin = lci, ymax = uci),
                colour = palette_contract["neutral_mid"],
                width = 0.18, linewidth = 0.5) +
  geom_point(size = 2.5, stroke = 0.3) +
  facet_wrap(~ scale, ncol = 1,
             labeller = labeller(scale = buffer_lab)) +
  scale_colour_manual(values = group_palette, name = NULL) +
  scale_shape_manual(values = group_shapes, name = NULL) +
  scale_x_discrete(labels = c(
    "Low EVI / low O3"   = expression(atop("Low EVI", "low O"[3])),
    "Low EVI / high O3"  = expression(atop("Low EVI", "high O"[3])),
    "High EVI / low O3"  = expression(atop("High EVI", "low O"[3])),
    "High EVI / high O3" = expression(atop("High EVI", "high O"[3]))
  )) +
  scale_y_continuous(breaks = scales::pretty_breaks(n = 5)) +
  labs(x = NULL, y = "Adjusted marginal mean BAA (years)") +
  theme(
    axis.ticks.x     = element_blank(),
    panel.grid.major.y = element_line(colour = "#ECECEC", linewidth = 0.3),
    plot.margin      = margin(6, 10, 4, 6)
  ) +
  guides(colour = guide_legend(nrow = 2, byrow = TRUE,
                                override.aes = list(size = 2.5)),
         shape  = guide_legend(nrow = 2, byrow = TRUE,
                                override.aes = list(size = 2.5)))

# ===========================================================================
# Panel b — Contrast forest plot
# ===========================================================================
cat("Building panel b: contrast forest plot...\n")

# Annotation text: compact format, placed to the right of each CI
# v5 (task T7): DiD rows additionally annotated with the minimum detectable
# interaction at 80% power (45_mde_tost.R)
mde_file <- "output/tables/did_mde_tost_v5.csv"
mde_map <- setNames(rep(NA_real_, 2), c("1KM", "500m"))
if (!file.exists(mde_file)) {
  # Pipeline-order guard: the MDE/TOST table is produced by 45_mde_tost.R.
  # Generate it in a subprocess when absent so Figure 3 renders identically
  # regardless of script invocation order (e.g. fresh master-run sequence).
  script45 <- if (file.exists("CODE/45_mde_tost.R")) "CODE/45_mde_tost.R" else "45_mde_tost.R"
  if (file.exists(script45)) {
    cat("MDE/TOST table not found; running", script45, "first...\n")
    system2(file.path(R.home("bin"), "Rscript"), shQuote(script45))
  }
}
if (file.exists(mde_file)) {
  mde_tab <- read.csv(mde_file, stringsAsFactors = FALSE)
  mde_map <- setNames(mde_tab$mde_80pct, mde_tab$scale)
}
forest <- forest %>%
  mutate(
    anno_text = ifelse(
      contrast == "Difference-in-differences interaction" &
        !is.na(mde_map[as.character(scale)]),
      sprintf("%+.2f [%+.2f, %+.2f] (MDE=%.1fy)",
              estimate, lci, uci, mde_map[as.character(scale)]),
      sprintf("%+.2f [%+.2f, %+.2f]  %s",
              estimate, lci, uci, ifelse(p < 0.05, "*", ""))),
    anno_x    = pmax(uci + 0.18, estimate + 0.8)
  )

p_b <- ggplot(forest, aes(x = estimate, y = ypos)) +
  geom_vline(xintercept = 0, linetype = "dashed",
             colour = palette_contract["neutral_light"], linewidth = 0.35) +
  geom_errorbar(aes(xmin = lci, xmax = uci,
                    colour = ifelse(is_sig, "p < 0.05", "p ≥ 0.05")),
                orientation = "y", linewidth = 0.7, width = 0.18) +
  geom_point(aes(shape = ctype,
                 colour = ifelse(is_sig, "p < 0.05", "p ≥ 0.05")),
             size = 2.3, stroke = 0.35) +
  geom_text(aes(x = anno_x, label = anno_text),
            hjust = 0, size = 2.0, family = "Arial",
            colour = palette_contract["neutral_dark"]) +
  facet_wrap(~ scale, ncol = 1,
             labeller = labeller(scale = buffer_lab)) +
  scale_y_reverse(
    breaks = seq_len(max(forest$ypos)),
    labels = levels(factor(forest$label, levels = rev(unique(forest$label))))
  ) +
  scale_colour_manual(
    name   = NULL,
    values = c("p < 0.05"          = palette_contract["accent_red"],
               "p ≥ 0.05"     = palette_contract["neutral_mid"])
  ) +
  scale_shape_manual(
    name   = "Contrast type",
    values = c("Pairwise vs. reference" = 16,
               "Within-stratum"         = 17,
               "Interaction"            = 18)
  ) +
  scale_x_continuous(breaks = scales::pretty_breaks(n = 5)) +
  # right padding must fit the ~30-character estimate annotations (incl. MDE)
  coord_cartesian(xlim = c(min(forest$lci) - 0.5,
                            max(forest$anno_x) + 5.6)) +
  labs(x = "Contrast estimate (years of BAA)", y = NULL) +
  theme(
    axis.ticks.y     = element_blank(),
    panel.grid.major.x = element_line(colour = "#ECECEC", linewidth = 0.3),
    plot.margin      = margin(6, 6, 4, 6)
  ) +
  guides(
    colour = guide_legend(order = 1, nrow = 1,
                          override.aes = list(shape = 16, size = 2.3)),
    shape  = guide_legend(order = 2, nrow = 2, byrow = TRUE)
  )

# ===========================================================================
# Assemble & export
# ===========================================================================
cat("Assembling and exporting...\n")

fig3 <- (p_a | p_b) +
  plot_annotation(tag_levels = "a") &
  theme(plot.tag = element_text(size = 9, face = "bold"))

# Nature double-column: 183 mm wide, ~210 mm tall (two stacked facets)
save_pub_r(fig3, out_stem, width_mm = 183, height_mm = 210, dpi = 600)

